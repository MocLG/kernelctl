/// Read a `KEY=value` setting from /etc/default/grub, unquoting the value.
pub fn default_grub_get(text: &str, key: &str) -> Option<String> {
    for line in text.lines() {
        let line = line.trim();
        if line.starts_with('#') {
            continue;
        }
        let Some((k, v)) = line.split_once('=') else { continue };
        if k.trim() != key {
            continue;
        }
        return Some(unquote(v.trim()));
    }
    None
}

/// Set a `KEY=value` setting, preserving comments and the rest of the file.
pub fn default_grub_set(text: &str, key: &str, value: &str) -> String {
    // Always quote: these values routinely contain spaces, and an unquoted
    // GRUB_CMDLINE_LINUX would be read by the shell as several assignments.
    let assignment = format!("{key}=\"{}\"", value.replace('"', "\\\""));
    let mut out = Vec::new();
    let mut replaced = false;

    for line in text.lines() {
        let is_key = !line.trim_start().starts_with('#')
            && line.split_once('=').is_some_and(|(k, _)| k.trim() == key);
        if is_key && !replaced {
            out.push(assignment.clone());
            replaced = true;
        } else if !is_key {
            out.push(line.to_string());
        }
    }
    if !replaced {
        out.push(assignment);
    }
    let mut joined = out.join("\n");
    joined.push('\n');
    joined
}

fn unquote(v: &str) -> String {
    let v = v.trim();
    if v.len() >= 2 {
        let b = v.as_bytes();
        if (b[0] == b'"' || b[0] == b'\'') && b[b.len() - 1] == b[0] {
            return v[1..v.len() - 1].to_string();
        }
    }
    // Strip a trailing comment from an unquoted value.
    v.split_once(" #").map(|(a, _)| a.trim().to_string()).unwrap_or_else(|| v.to_string())
}

