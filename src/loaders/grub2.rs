/// A menu entry as it appears in grub.cfg.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct MenuEntry {
    pub title: String,
    /// Value of `$menuentry_id_option`, which is what `saved_entry` stores.
    pub id: Option<String>,
    pub kernel: Option<String>,
    pub cmdline: String,
    pub initrds: Vec<String>,
    pub devicetree: Option<String>,
    /// GRUB's positional address, e.g. `0` or `1>2` inside a submenu.
    pub index_path: String,
    pub depth: u8,
    pub is_submenu: bool,
    /// Line index of the `linux` line, so a cmdline edit can target it.
    pub linux_line: Option<usize>,
}

/// Split a grub.cfg line into shell-style tokens, honouring quotes.
///
/// GRUB's config language is shell-like: titles are quoted and may contain
/// spaces and braces, so a naive whitespace split mis-parses them and a naive
/// brace count loses track of nesting.
fn tokenize(line: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut quote: Option<char> = None;
    let mut escaped = false;
    let mut has = false;

    for ch in line.chars() {
        if escaped {
            cur.push(ch);
            escaped = false;
            has = true;
            continue;
        }
        match ch {
            '\\' if quote != Some('\'') => escaped = true,
            '\'' | '"' if quote.is_none() => {
                quote = Some(ch);
                has = true;
            }
            c if Some(c) == quote => {
                quote = None;
                has = true;
            }
            c if c.is_whitespace() && quote.is_none() => {
                if has {
                    out.push(std::mem::take(&mut cur));
                    has = false;
                }
            }
            c => {
                cur.push(c);
                has = true;
            }
        }
    }
    if has {
        out.push(cur);
    }
    out
}

/// Net brace depth change on a line, ignoring braces inside quotes.
fn brace_delta(line: &str) -> i32 {
    let mut depth = 0;
    let mut quote: Option<char> = None;
    let mut escaped = false;

    for ch in line.chars() {
        if escaped {
            escaped = false;
            continue;
        }
        match ch {
            '\\' if quote != Some('\'') => escaped = true,
            '\'' | '"' if quote.is_none() => quote = Some(ch),
            c if Some(c) == quote => quote = None,
            '{' if quote.is_none() => depth += 1,
            '}' if quote.is_none() => depth -= 1,
            // A comment runs to end of line, so stop counting.
            '#' if quote.is_none() => break,
            _ => {}
        }
    }
    depth
}

/// Extract the menuentry id from a `menuentry`/`submenu` line.
///
/// Generated configs write `$menuentry_id_option 'gnulinux-...'`; hand-written
/// ones use `--id foo`. Both forms put the id in the token after the marker.
fn extract_id(tokens: &[String]) -> Option<String> {
    tokens
        .iter()
        .position(|t| t == "$menuentry_id_option" || t == "--id")
        .and_then(|i| tokens.get(i + 1))
        .cloned()
}

/// Parse every entry out of a grub.cfg.
pub fn parse_cfg(text: &str) -> Vec<MenuEntry> {
    let lines: Vec<&str> = text.lines().collect();
    let mut out: Vec<MenuEntry> = Vec::new();

    // One counter per nesting level, giving GRUB's `1>2` addressing.
    let mut counters: Vec<usize> = vec![0];
    // Brace depth at which each open submenu started, so we know when it ends.
    let mut submenu_depths: Vec<i32> = Vec::new();
    let mut depth: i32 = 0;

    let mut i = 0;
    while i < lines.len() {
        let line = lines[i];
        let trimmed = line.trim_start();
        let tokens = tokenize(trimmed);
        let keyword = tokens.first().map(String::as_str).unwrap_or("");

        if keyword == "menuentry" || keyword == "submenu" {
            let is_submenu = keyword == "submenu";
            // The first token after the keyword that is not a flag is the
            // title. Generated configs put it immediately after.
            let title = tokens.get(1).cloned().unwrap_or_default();
            let level = counters.len() - 1;

            let mut index_path = String::new();
            for (n, c) in counters.iter().enumerate() {
                if n > 0 {
                    index_path.push('>');
                }
                index_path.push_str(&c.to_string());
            }

            let mut entry = MenuEntry {
                title,
                id: extract_id(&tokens),
                index_path,
                depth: level as u8,
                is_submenu,
                ..Default::default()
            };

            depth += brace_delta(line);

            if is_submenu {
                // Descend: children are numbered from zero within the submenu.
                // The parent's counter is deliberately *not* advanced yet -
                // children address as `parent>child` using the parent's own
                // index, so it must keep that value until the submenu closes.
                submenu_depths.push(depth);
                counters.push(0);
                out.push(entry);
                i += 1;
                continue;
            }
            *counters.last_mut().unwrap() += 1;

            // A menuentry body runs until the brace depth returns to where it
            // was before the opening brace.
            let body_start_depth = depth;
            let mut j = i + 1;
            while j < lines.len() && depth >= body_start_depth {
                let body_line = lines[j];
                parse_body_line(&mut entry, body_line, j);
                depth += brace_delta(body_line);
                if depth < body_start_depth {
                    break;
                }
                j += 1;
            }
            out.push(entry);
            i = j + 1;

            // Leaving a menuentry can also close the submenu containing it.
            close_submenus(depth, &mut submenu_depths, &mut counters);
            continue;
        }

        depth += brace_delta(line);
        // A closing brace may end a submenu.
        close_submenus(depth, &mut submenu_depths, &mut counters);
        i += 1;
    }

    out
}

/// Pop any submenus whose closing brace we have now passed.
///
/// The parent's counter is advanced here rather than when the submenu opened:
/// while we are inside it, children address themselves as `parent>child` and
/// need the parent's own index to still be current.
fn close_submenus(depth: i32, submenu_depths: &mut Vec<i32>, counters: &mut Vec<usize>) {
    while submenu_depths.last().is_some_and(|d| depth < *d) {
        submenu_depths.pop();
        if counters.len() > 1 {
            counters.pop();
            *counters.last_mut().expect("a parent level always remains") += 1;
        }
    }
}

/// Pull kernel, initrd and devicetree out of one line of a menuentry body.
fn parse_body_line(entry: &mut MenuEntry, line: &str, line_no: usize) {
    let tokens = tokenize(line.trim_start());
    let Some(keyword) = tokens.first() else { return };

    match keyword.as_str() {
        // linux16 and linuxefi are the BIOS and EFI variants; all three take
        // the kernel path first and the command line after it.
        "linux" | "linux16" | "linuxefi" => {
            if let Some(path) = tokens.get(1) {
                entry.kernel = Some(path.clone());
                entry.cmdline = tokens[2..].join(" ");
                entry.linux_line = Some(line_no);
            }
        }
        "initrd" | "initrd16" | "initrdefi" => {
            // A single initrd line may list several images.
            entry.initrds.extend(tokens[1..].iter().cloned());
        }
        "devicetree" => entry.devicetree = tokens.get(1).cloned(),
        _ => {}
    }
}

