impl Grub2 {
    pub fn detect(roots: &BootRoots) -> Option<Grub2> {
        for root in &roots.boot {
            // Debian and Arch use grub/, Fedora and SUSE use grub2/.
            for name in ["grub", "grub2"] {
                let dir = root.join(name);
                let cfg = dir.join("grub.cfg");
                let _ = &dir;
                if !cfg.is_file() {
                    continue;
                }
                let env = dir.join("grubenv");
                // A writable environment block means set-default and set-next
                // work without regenerating the menu, so it is worth more than
                // a lone config file.
                let confidence = if env.exists() { 92 } else { 80 };
                return Some(Grub2 {
                    cfg,
                    default_grub: roots.find_config("default/grub"),
                    env,
                    boot_root: root.clone(),
                    confidence,
                });
            }
        }
        None
    }

    fn load_env(&self) -> GrubEnv {
        GrubEnv::load(&self.env).unwrap_or_else(|_| GrubEnv::empty())
    }

    /// Does grub.cfg actually consult `saved_entry`?
    ///
    /// It only does so when the config was generated with `GRUB_DEFAULT=saved`.
    /// Without that, writing the environment block has no effect and the user
    /// needs to be told.
    fn honours_saved_entry(&self) -> bool {
        std::fs::read_to_string(&self.cfg)
            .map(|t| t.contains("saved_entry"))
            .unwrap_or(false)
    }

    fn default_grub_path(&self) -> Option<PathBuf> {
        self.default_grub.clone()
    }

    /// Resolve which parsed entry the given `saved_entry`/`next_entry` value
    /// refers to. GRUB accepts an id, a title or a positional index.
    fn value_matches(value: &str, entry: &MenuEntry) -> bool {
        let value = value.trim();
        if value.is_empty() {
            return false;
        }
        entry.id.as_deref() == Some(value)
            || entry.title == value
            || entry.index_path == value
    }
}

fn timeout_to_grub(t: Timeout) -> String {
    match t {
        Timeout::Immediate => "0".into(),
        Timeout::Seconds(n) => n.to_string(),
        // GRUB spells "wait forever" as -1.
        Timeout::Indefinite => "-1".into(),
    }
}

fn timeout_from_grub(v: &str) -> Option<Timeout> {
    let v = v.trim();
    if v == "-1" {
        return Some(Timeout::Indefinite);
    }
    match v.parse::<u32>() {
        Ok(0) => Some(Timeout::Immediate),
        Ok(n) => Some(Timeout::Seconds(n)),
        Err(_) => None,
    }
}

/// Replace the command line on a specific `linux` line of grub.cfg.
fn rewrite_linux_line(text: &str, line_no: usize, cmdline: &str) -> Result<String> {
    let mut lines: Vec<String> = text.lines().map(str::to_string).collect();
    let line = lines
        .get(line_no)
        .ok_or_else(|| Error::other("grub.cfg changed on disk since it was read"))?;

    let indent: String = line.chars().take_while(|c| c.is_whitespace()).collect();
    let tokens = tokenize(line.trim_start());
    let keyword = tokens.first().cloned().unwrap_or_else(|| "linux".into());
    let kernel = tokens.get(1).cloned().unwrap_or_default();

    lines[line_no] = format!("{indent}{keyword} {kernel} {cmdline}").trim_end().to_string();

    let mut joined = lines.join("\n");
    joined.push('\n');
    Ok(joined)
}

impl Bootloader for Grub2 {
    fn kind(&self) -> LoaderKind {
        LoaderKind::Grub2
    }

    fn capabilities(&self) -> Capabilities {
        Capabilities::SET_DEFAULT
            | Capabilities::SET_ONESHOT
            | Capabilities::TIMEOUT
            | Capabilities::EDIT_CMDLINE
            | Capabilities::GENERATED
    }

    fn confidence(&self) -> u8 {
        self.confidence
    }

    fn config_files(&self) -> Vec<PathBuf> {
        [Some(self.cfg.clone()), Some(self.env.clone()), self.default_grub.clone()]
            .into_iter()
            .flatten()
            .filter(|p| p.exists())
            .collect()
    }

    fn post_write_note(&self) -> Option<String> {
        Some(format!(
            "{} is generated by grub-mkconfig and will be rewritten on the next \
             kernel upgrade; settings mirrored into /etc/default/grub survive that",
            self.cfg.display()
        ))
    }

    fn entries(&self, _ctx: &Context) -> Result<Vec<BootEntry>> {
        let text = atomic::read_to_string(&self.cfg)?;
        let parsed = parse_cfg(&text);
        let env = self.load_env();
        let saved = env.get(VAR_SAVED).unwrap_or_default().to_string();
        let next = env.get(VAR_NEXT).unwrap_or_default().to_string();

        let mut out = Vec::new();
        for menu in &parsed {
            // saved_entry stores the id when there is one, so prefer it and
            // fall back to the positional address.
            let native_id = menu.id.clone().unwrap_or_else(|| menu.index_path.clone());
            let mut entry =
                BootEntry::new(LoaderKind::Grub2, &self.cfg, &native_id, &menu.title);

            entry.kernel = menu.kernel.as_deref().map(|p| resolve_under(&self.boot_root, p));
            entry.initrds =
                menu.initrds.iter().map(|p| resolve_under(&self.boot_root, p)).collect();
            entry.devicetree =
                menu.devicetree.as_deref().map(|p| resolve_under(&self.boot_root, p));
            entry.cmdline = menu.cmdline.clone();
            entry.depth = menu.depth;

            if menu.is_submenu {
                entry.flags.insert(EntryFlags::SUBMENU);
            }
            if !saved.is_empty() && Grub2::value_matches(&saved, menu) {
                entry.flags.insert(EntryFlags::DEFAULT);
            }
            if !next.is_empty() && Grub2::value_matches(&next, menu) {
                entry.flags.insert(EntryFlags::ONESHOT);
            }

            entry.extra.insert("index".into(), menu.index_path.clone());
            if let Some(line) = menu.linux_line {
                entry.extra.insert("cfg-line".into(), (line + 1).to_string());
            }

            out.push(entry);
        }

        // Nothing in grubenv: fall back to the static `set default=` the
        // generated config carries.
        if saved.is_empty() {
            if let Some(value) = text
                .lines()
                .find_map(|l| l.trim().strip_prefix("set default="))
                .map(|v| unquote(v.trim()))
            {
                if !value.contains("saved_entry") {
                    if let Some(e) = out
                        .iter_mut()
                        .zip(parsed.iter())
                        .find(|(_, m)| Grub2::value_matches(&value, m))
                        .map(|(e, _)| e)
                    {
                        e.flags.insert(EntryFlags::DEFAULT);
                    }
                }
            }
        }

        Ok(out)
    }

    fn set_default(&self, ctx: &Context, entry: &BootEntry) -> Result<Vec<WriteOutcome>> {
        ctx.preflight_write("set-default", &self.env)?;
        if ctx.dry_run {
            return Ok(Vec::new());
        }

        let mut env = self.load_env();
        env.set(VAR_SAVED, &entry.native_id)?;
        grubenv::write_in_place(&self.env, &env)?;

        let mut outcomes = vec![WriteOutcome {
            target: self.env.clone(),
            backup: Some(atomic::backup_path_for(&self.env)),
        }];

        // Writing saved_entry only has an effect if the generated menu reads
        // it, which requires GRUB_DEFAULT=saved. Set that too, so the choice
        // survives the next grub-mkconfig run.
        if !self.honours_saved_entry() {
            if let Some(path) = self.default_grub_path() {
                let text = atomic::read_to_string(&path)?;
                if default_grub_get(&text, "GRUB_DEFAULT").as_deref() != Some("saved") {
                    let updated = default_grub_set(&text, "GRUB_DEFAULT", "saved");
                    outcomes.push(atomic::write_atomic(&path, updated.as_bytes())?);
                }
            }
        }

        Ok(outcomes)
    }

    fn set_oneshot(&self, ctx: &Context, entry: &BootEntry) -> Result<Vec<WriteOutcome>> {
        ctx.preflight_write("set-next", &self.env)?;
        if ctx.dry_run {
            return Ok(Vec::new());
        }
        let mut env = self.load_env();
        env.set(VAR_NEXT, &entry.native_id)?;
        grubenv::write_in_place(&self.env, &env)?;
        Ok(vec![WriteOutcome {
            target: self.env.clone(),
            backup: Some(atomic::backup_path_for(&self.env)),
        }])
    }

    fn clear_oneshot(&self, ctx: &Context) -> Result<Vec<WriteOutcome>> {
        ctx.preflight_write("set-next --clear", &self.env)?;
        if ctx.dry_run {
            return Ok(Vec::new());
        }
        let mut env = self.load_env();
        env.remove(VAR_NEXT);
        grubenv::write_in_place(&self.env, &env)?;
        Ok(vec![WriteOutcome {
            target: self.env.clone(),
            backup: Some(atomic::backup_path_for(&self.env)),
        }])
    }

    fn timeout(&self, _ctx: &Context) -> Result<Option<Timeout>> {
        // /etc/default/grub is the source of truth; grub.cfg only reflects the
        // last time it was generated.
        if let Some(path) = self.default_grub_path() {
            if let Ok(text) = std::fs::read_to_string(&path) {
                if let Some(t) = default_grub_get(&text, "GRUB_TIMEOUT").as_deref().and_then(timeout_from_grub) {
                    return Ok(Some(t));
                }
            }
        }
        let Ok(cfg) = std::fs::read_to_string(&self.cfg) else { return Ok(None) };
        Ok(cfg
            .lines()
            .find_map(|l| l.trim().strip_prefix("set timeout="))
            .map(|v| unquote(v.trim()))
            .as_deref()
            .and_then(timeout_from_grub))
    }

    fn set_timeout(&self, ctx: &Context, timeout: Timeout) -> Result<Vec<WriteOutcome>> {
        ctx.preflight_write("timeout", &self.cfg)?;
        if ctx.dry_run {
            return Ok(Vec::new());
        }
        let value = timeout_to_grub(timeout);
        let mut outcomes = Vec::new();

        // Write the template so the change survives regeneration...
        if let Some(path) = self.default_grub_path() {
            let text = atomic::read_to_string(&path)?;
            let updated = default_grub_set(&text, "GRUB_TIMEOUT", &value);
            outcomes.push(atomic::write_atomic(&path, updated.as_bytes())?);
        }

        // ...and the generated menu so it takes effect on the next boot
        // without waiting for grub-mkconfig.
        let cfg_text = atomic::read_to_string(&self.cfg)?;
        let mut lines: Vec<String> = cfg_text.lines().map(str::to_string).collect();
        let mut patched = false;
        for line in lines.iter_mut() {
            if line.trim().starts_with("set timeout=") {
                let indent: String = line.chars().take_while(|c| c.is_whitespace()).collect();
                *line = format!("{indent}set timeout={value}");
                patched = true;
            }
        }
        if patched {
            let mut joined = lines.join("\n");
            joined.push('\n');
            outcomes.push(atomic::write_atomic(&self.cfg, joined.as_bytes())?);
        }

        Ok(outcomes)
    }

    fn set_cmdline(&self, ctx: &Context, entry: &BootEntry, cmdline: &str) -> Result<Vec<WriteOutcome>> {
        ctx.preflight_write("cmdline set", &self.cfg)?;

        let line_no = entry
            .extra
            .get("cfg-line")
            .and_then(|s| s.parse::<usize>().ok())
            .map(|n| n - 1)
            .ok_or_else(|| {
                Error::validation("this entry has no kernel line to edit".to_string())
            })?;

        if ctx.dry_run {
            return Ok(Vec::new());
        }

        let text = atomic::read_to_string(&self.cfg)?;
        let updated = rewrite_linux_line(&text, line_no, cmdline)?;
        Ok(vec![atomic::write_atomic(&self.cfg, updated.as_bytes())?])
    }
}

